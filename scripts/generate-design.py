#!/usr/bin/env python3
"""Generate shared native design values and branding. Run --check to detect drift.
Reference: Keyflow styles.css, stores/theme.svelte.ts and KeyboardKeyDisplay.svelte.
No Svelte runtime or UI source is copied into the native apps.
"""
import argparse
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
brand = json.loads((ROOT / 'Design/brand.json').read_text())
check = argparse.ArgumentParser()
check.add_argument('--check', action='store_true')
args = check.parse_args()
stale = []
def write(path, value):
    target = ROOT / path
    if target.exists() and target.read_text() == value: return
    if args.check: stale.append(path)
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(value)
def update(path, transform):
    write(path, transform((ROOT / path).read_text()))
def quoted(value): return json.dumps(value, ensure_ascii=False)
# Stable Keyflow byte-slot hues. Persist the values in generated tables so all
# hosts agree without porting the JS library or duplicating its implementation.
labels = {**{chr(i): i for i in range(33,127)}, 'Shift':16, 'mode':16, 'space':32, '⌫':8, '↵':13}
def hue(index):
    cycle, offset = divmod(index, 8)
    reverse = int(f'{cycle:05b}'[::-1], 2)
    return (reverse + offset * 32) * 360 / 256
hues = {k: hue(i) for k,i in labels.items()}
swift = '// Generated by scripts/generate-design.py. Edit Design/brand.json.\nimport Foundation\n\nenum AppDesign {\n'
for key in ['name']:
    swift += f'    static let {key} = {quoted(brand[key])}\n'
for key in ['keyRadius','panelRadius','borderWidth']:
    swift += f'    static let {key}: Double = {brand[key]}\n'
for mode in ['light','dark']:
    for key,value in brand[mode].items():
        swift += f'    static let {mode}{key.title()}: UInt32 = 0x{value[1:]}\n'
swift += '    static let keyHues: [String: Double] = [\n' + ''.join(f'        {quoted(k)}: {v},\n' for k,v in hues.items()) + '    ]\n}\n'
write('Sources/Core/AppDesign.swift',swift)
kotlin = '// Generated by scripts/generate-design.py. Edit Design/brand.json.\npackage com.minh.sieuviet.android\n\nobject AppDesign {\n'
for key in ['name']:
    kotlin += f'    const val {key} = {quoted(brand[key])}\n'
for key in ['keyRadius','panelRadius','borderWidth']:
    kotlin += f'    const val {key} = {brand[key]}\n'
for mode in ['light','dark']:
    for key,value in brand[mode].items():
        kotlin += f'    const val {mode}{key.title()} = {quoted(value)}\n'
kotlin += '    val keyHues = mapOf(\n' + ''.join(f'        {quoted(k)} to {v}f,\n' for k,v in hues.items()) + '    )\n}\n'
write('Android/app/src/main/kotlin/com/minh/sieuviet/android/AppDesign.kt',kotlin)
write('Android/app/src/main/res/values/strings.xml',f'<resources>\n    <string name="app_name">{escape(brand["name"])}</string>\n</resources>\n')
for path in ['Resources/Info.plist','iOS/App/Info.plist','iOS/KeyboardExtension/Info.plist']:
    update(path, lambda s: re.sub(r'(<key>CFBundle(?:DisplayName|Name)</key>\s*<string>).*?(</string>)',lambda m:m[1]+brand['name']+m[2],s))
update('Android/app/src/main/AndroidManifest.xml',lambda s:re.sub(r'android:label="[^"]*"','android:label="@string/app_name"',s))
update('Android/app/src/main/res/xml/input_method.xml',lambda s:re.sub(r'android:label="[^"]*"','android:label="@string/app_name"',s))
for mode, folder, parent in [('light','values','Theme.Material.Light.NoActionBar'),('dark','values-night','Theme.Material.NoActionBar')]:
    write(f'Android/app/src/main/res/{folder}/styles.xml', f'''<!-- Generated from Design/brand.json. -->
<resources>
    <style name="AppTheme" parent="android:style/{parent}">
        <item name="android:fontFamily">monospace</item>
        <item name="android:colorAccent">{brand[mode]['ink']}</item>
        <item name="android:windowLightStatusBar">{str(mode == 'light').lower()}</item>
        <item name="android:windowActionModeOverlay">true</item>
        <item name="android:windowBackground">{brand[mode]['background']}</item>
    </style>
</resources>
''')
points = brand['star']
path = 'M' + 'L'.join(f'{x*100:g},{y*100:g}' for x,y in points) + 'Z'
write('Android/app/src/main/res/drawable/ic_sieuviet.xml',f'''<!-- Generated from Design/brand.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="100" android:viewportHeight="100">
    <path android:fillColor="#FFFFFF" android:pathData="M0,0h100v100h-100z" />
    <path android:fillColor="#333333" android:pathData="{path}" />
</vector>
''')
# Reuse exactly the same foreground for Android's system-masked adaptive icon.
write('Android/app/src/main/res/drawable/ic_star.xml',f'''<!-- Generated from Design/brand.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="100" android:viewportHeight="100">
    <path android:fillColor="#333333" android:pathData="{path}" />
</vector>
''')
write('Android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml','''<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@android:color/white" />
    <foreground android:drawable="@drawable/ic_star" />
    <monochrome android:drawable="@drawable/ic_star" />
</adaptive-icon>
''')
update('Android/app/src/main/AndroidManifest.xml',lambda s:s.replace('android:icon="@drawable/ic_sieuviet"','android:icon="@mipmap/ic_launcher"'))
# One release version/build number across all supported platforms.
for path in ['Resources/Info.plist']:
    update(path,lambda s:re.sub(r'(<key>CFBundleShortVersionString</key>\s*<string>).*?(</string>)',lambda m:m[1]+brand['version']+m[2],s))
    update(path,lambda s:re.sub(r'(<key>CFBundleVersion</key>\s*<string>).*?(</string>)',lambda m:m[1]+str(brand['build'])+m[2],s))
write('Design/version.properties',f"version={brand['version']}\nbuild={brand['build']}\n")
# Shared bilingual interface content; Vietnamese is the explicit default.
content = json.loads((ROOT / 'Design/content.json').read_text())
for key, value in content.items():
    if set(value) != {'vi','en'}: raise SystemExit(f'Missing translation: {key}')
    if set(re.findall(r'\{(\w+)\}', value['vi'])) != set(re.findall(r'\{(\w+)\}', value['en'])):
        raise SystemExit(f'Translation placeholders differ: {key}')
swift = '// Generated by scripts/generate-design.py. Edit Design/content.json.\nimport Foundation\n\nenum AppCopy {\n    static var language = "vi"\n    static let didChange = Notification.Name("sieuviet.languageChanged")\n    static func text(_ key: String, _ values: [String: String] = [:]) -> String {\n        var result = (language == "en" ? english : vietnamese)[key] ?? key\n        for (name, value) in values { result = result.replacingOccurrences(of: "{\\(name)}", with: value) }\n        return result\n    }\n'
for code, name in [('vi','vietnamese'),('en','english')]:
    swift += f'    private static let {name}: [String: String] = [\n' + ''.join(f'        {quoted(k)}: {quoted(v[code])},\n' for k,v in content.items()) + '    ]\n'
write('Sources/Core/AppCopy.swift',swift+'}\n')
kotlin = '// Generated by scripts/generate-design.py. Edit Design/content.json.\npackage com.minh.sieuviet.android\n\nobject AppCopy {\n    var language = "vi"\n    fun text(key: String, vararg values: Pair<String, String>): String {\n        var result = (if (language == "en") english else vietnamese)[key] ?: key\n        for ((name, value) in values) result = result.replace("{${name}}", value)\n        return result\n    }\n'
for code, name in [('vi','vietnamese'),('en','english')]:
    kotlin += f'    private val {name} = mapOf(\n' + ''.join(f'        {quoted(k)} to {quoted(v[code])},\n' for k,v in content.items()) + '    )\n'
write('Android/app/src/main/kotlin/com/minh/sieuviet/android/AppCopy.kt',kotlin+'}\n')
# Desktop native renderers consume the same brand/content catalogs.
star_path = 'M' + 'L'.join(f'{x*100:g},{y*100:g}' for x,y in brand['star']) + 'Z'
write('Desktop/common/icon.svg',f'<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100"><path fill="{brand["light"]["ink"]}" d="{star_path}"/></svg>\n')
write('Desktop/common/design.json',json.dumps({'brand':brand,'copy':content},ensure_ascii=False,indent=2)+'\n')
cpp = '// Generated by scripts/generate-design.py. Edit Design catalogs.\n#pragma once\n#include <string>\n#include <string_view>\nnamespace sv::design {\n'
for key in ['name','version']:
    cpp += f'inline constexpr const char *{key} = {quoted(brand[key])};\n'
cpp += 'struct Copy { std::string_view key; const char *vi; const char *en; };\ninline constexpr Copy copy[] = {\n'
cpp += ''.join(f'    {{{quoted(key)}, {quoted(value["vi"])}, {quoted(value["en"])}}},\n' for key,value in content.items())
cpp += '};\ninline std::string text(std::string_view key, const std::string &language = "vi") {\n    for (const auto &entry : copy) if (entry.key == key) return language == "en" ? entry.en : entry.vi;\n    return std::string(key);\n}\n}\n'
write('Desktop/common/Design.hpp',cpp)
if stale: raise SystemExit('Generated design is stale: ' + ', '.join(stale))
print('Shared design ' + ('verified' if args.check else 'generated'))
